"""Compile shaders/pack.hlsl with the Windows SDK's fxc and write src/shaderpack_data.h (DWORD arrays).
Each program gets a ps_2_a build (with specular anti-aliasing, needs gradient instructions) and a plain ps_2_0
fallback. Run from the repository root:  python tools/build_shaders.py"""
import glob, os, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'shaders', 'pack.hlsl')
OUT = os.path.join(ROOT, 'src', 'shaderpack_data.h')
PROGRAMS = ['A', 'B', 'C', 'D', 'E']
TARGETS = [('ps_2_a', '2a', ['/DSPEC_AA=1']), ('ps_2_0', '20', [])]

def find_fxc():
    hits = sorted(glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x86\fxc.exe'))
    if not hits:
        sys.exit('fxc.exe not found (install the Windows SDK)')
    return hits[-1]

def main():
    fxc = find_fxc()
    lines = ['// Generated by tools/build_shaders.py from shaders/pack.hlsl - do not edit.', '#pragma once', '#include <cstdint>', '']
    with tempfile.TemporaryDirectory() as tmp:
        jobs = [(prog, target, suffix, defs) for prog in PROGRAMS for target, suffix, defs in TARGETS]
        jobs.append(('Magenta', 'ps_2_0', '20', []))   # F11 highlight tool
        for prog, target, suffix, defs in jobs:
            if True:
                cso = os.path.join(tmp, 'ps%s_%s.cso' % (prog, suffix))
                cmd = [fxc, '/nologo', '/O3', '/T', target, '/E', 'PS_' + prog, '/Fo', cso] + defs + [SRC]
                r = subprocess.run(cmd, capture_output=True, text=True)
                if r.returncode != 0:
                    sys.exit('fxc failed for PS_%s %s:\n%s%s' % (prog, target, r.stdout, r.stderr))
                data = open(cso, 'rb').read()
                words = struct.unpack('<%dI' % (len(data) // 4), data)
                name = 'kPack%s_%s' % (prog, suffix)
                lines.append('// PS_%s, %s (%d tokens)' % (prog, target, len(words)))
                lines.append('alignas(4) static const uint32_t %s[] = {' % name)
                for i in range(0, len(words), 8):
                    lines.append('    ' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + ',')
                lines.append('};')
                lines.append('')
                print('PS_%s %-7s %4d tokens' % (prog, target, len(words)))
    open(OUT, 'w', newline='\n').write('\n'.join(lines))
    print('wrote', OUT)

if __name__ == '__main__':
    main()
