"""Write src/shaderpack_families.h: every unique ps_1_1 shader embedded in splintercell3.exe (FNV-1a hash of its
bytecode + token count) with a family, for the shader pack's F11 highlight tool. Needs the exe and D3DX9 (for the
disassembly the classification reads).  usage: python tools/gen_shader_families.py <path-to-splintercell3.exe>"""
import ctypes, os, re, struct, sys
from ctypes import POINTER, byref, c_uint32, c_void_p

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'src', 'shaderpack_families.h')

d3dx = ctypes.WinDLL(r'C:\Windows\System32\d3dx9_43.dll')
dis = d3dx.D3DXDisassembleShader
dis.argtypes = [POINTER(c_uint32), ctypes.c_int, ctypes.c_char_p, POINTER(c_void_p)]

def disasm(toks):
    arr = (c_uint32 * len(toks))(*toks)
    buf = c_void_p()
    if dis(arr, 0, None, byref(buf)) != 0:
        return None
    vt = ctypes.cast(ctypes.cast(buf, POINTER(c_void_p))[0], POINTER(c_void_p))
    ptr = ctypes.WINFUNCTYPE(c_void_p, c_void_p)(vt[3])(buf)
    size = ctypes.WINFUNCTYPE(ctypes.c_size_t, c_void_p)(vt[4])(buf)
    text = ctypes.string_at(ptr, size).decode('latin1')
    ctypes.WINFUNCTYPE(c_uint32, c_void_p)(vt[2])(buf)
    return text

def family(text):
    body = [l.strip().lstrip('+ ').strip() for l in text.splitlines() if l.strip() and not l.strip().startswith('//')][1:]
    bump = any(re.search(r'dp3\S* .*_bx2', l) for l in body)
    refl = any(re.search(r'mad_x2 r\d\.xyz, r\d, r\d_bx2, -t\d_bias', l) for l in body)
    powc = sum(1 for l in body if re.match(r'mul\S* r\d\.w, r\d(\.w)?, r\d(\.w)?$', l) or 'x4_sat' in l)
    dp3 = sum(1 for l in body if l.startswith('dp3'))
    tex = sum(1 for l in body if l.startswith('tex '))
    if refl or powc >= 2: return 0, len(body)
    if bump and dp3 >= 2: return 1, len(body)
    if bump: return 2, len(body)
    if dp3: return 3, len(body)
    if tex >= 2: return 4, len(body)
    return 5, len(body)

FAMILIES = ['specular', 'bump lighting, 2 lights', 'bump lighting', 'dot product (no bump map)', 'multi-texture', 'simple']

def main():
    data = open(sys.argv[1], 'rb').read()
    seen = {}
    for m in re.finditer(re.escape(struct.pack('<I', 0xFFFF0101)), data):
        o = m.start()
        if o % 4: continue
        toks = []
        p = o
        while p + 4 <= len(data) and len(toks) < 200:
            t = struct.unpack_from('<I', data, p)[0]; toks.append(t); p += 4
            if t == 0x0000FFFF: break
        if toks[-1] != 0x0000FFFF: continue
        text = disasm(toks)
        if not text: continue
        h = 2166136261
        for d in toks: h ^= d; h = (h * 16777619) & 0xFFFFFFFF
        if (h, len(toks)) in seen: continue
        fam, n = family(text)
        seen[(h, len(toks))] = (fam, n)
    rows = sorted(seen.items(), key=lambda kv: (kv[1][0], kv[0][0]))
    lines = ['// Generated by tools/gen_shader_families.py - every unique ps_1_1 shader in splintercell3.exe.', '#pragma once',
             '#include <cstdint>', '',
             'static const char* const kFamilyNames[] = { ' + ', '.join('"%s"' % f for f in FAMILIES) + ' };',
             'struct GameShader { uint32_t hash; uint16_t length; uint8_t family; uint8_t instructions; };',
             'static const GameShader kGameShaders[] = {']
    for (h, n), (fam, instr) in rows:
        lines.append('    { 0x%08X, %3d, %d, %2d },' % (h, n, fam, instr))
    lines += ['};', '']
    open(OUT, 'w', newline='\n').write('\n'.join(lines))
    from collections import Counter
    print('unique ps_1_1 shaders:', len(rows), dict(Counter(FAMILIES[v[0]] for v in seen.values())))

if __name__ == '__main__':
    main()
